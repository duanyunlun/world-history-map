BAIKE = 'https://baike.baidu.com/item/%s'
BING = 'https://www.bing.com/search?q=%s'


def baike_url(term):
    return BAIKE % urllib.parse.quote(term, safe='')


def bing_url(q):
    return BING % urllib.parse.quote(q, safe='')


def search_term(title):
    t = re.sub(r'[（(【\[].*?[）)】\]]', '', title)
    t = re.sub(r'^(中国|全国)?', '', t)
    return t[:24] or title[:24]


def build_sources(e):
    title = e['title']
    term = TERM.get(title)
    if not term:
        for k, v in TERM.items():
            if k and (k in title or title in k):
                term = v; break
    forced_search = any(k in title for k in NO_BAIKE) or len(title) > 22
    out = []
    if term and not forced_search:
        out.append({'t': '百度百科·%s' % term, 'u': baike_url(term)})
    q = search_term(title)
    out.append({'t': '必应检索·%s' % q, 'u': bing_url(q)})
    if len(out) < 2:
        key = title[:20]
        out.append({'t': '百度检索·%s' % key, 'u': 'https://www.baidu.com/s?wd=' + urllib.parse.quote(key)})
    return out[:3]


def verify(sample):
    """抽样实测链接可达性（200/301/302 视为存在）"""
    ok = bad = err = 0
    for u in sample:
        try:
            r = subprocess.run(['curl', '-sSL', '-o', '/dev/null', '-w', '%{http_code}',
                                '--max-time', '20', '-A', UA, u],
                               capture_output=True, text=True, timeout=25)
            code = r.stdout.strip()
        except Exception:
            code = '000'
        if code in ('200', '301', '302', '303'):
            ok += 1
        elif code in ('403', '000'):
            err += 1          # 反爬或网络限制，非「不存在」
        else:
            bad += 1
            print('   ✗ %s -> %s' % (code, urllib.parse.unquote(u)[:100]))
    return ok, bad, err


def main():
    d = json.load(open(EVF, encoding='utf-8'))
    evs = d['events'] if isinstance(d, dict) else d
    for e in evs:
        if not e.get('sources'):
            e['sources'] = build_sources(e)
    json.dump({'events': evs}, open(EVF, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    hosts = collections.Counter(re.sub(r'^https?://([^/]+).*$', r'\1', s['u'])
                               for e in evs for s in e['sources'])
    print('已回填来源：%d 条事件，%d 个不同链接' % (len(evs), len(set(s['u'] for e in evs for s in e['sources']))))
    print('来源域名：%s' % ', '.join('%s(%d)' % kv for kv in hosts.most_common()))
    if '--verify' in sys.argv:
        baike = sorted(set(s['u'] for e in evs for s in e['sources'] if 'baike.baidu.com' in s['u']))
        random.seed(7)
        sample = random.sample(baike, min(28, len(baike)))
        print('抽样实测 %d 个百度百科直达链接（200/30x=存在，403/000=反爬或网络受限，404=词条不存在）…' % len(sample))
        ok, bad, err = verify(sample)
        print('   结果：存在 %d ｜ 不存在 %d ｜ 反爬/受限 %d' % (ok, bad, err))


if __name__ == '__main__':
    main()
