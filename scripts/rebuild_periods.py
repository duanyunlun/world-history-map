def u(name, cities, key=None, fb=None):
    o = {'name': name, 'cities': cities}
    if key:
        o['key'] = key
    if fb:
        o['factionFrom'] = fb
    return o


def P(label, y, m, y2, m2, note, units=None, merge=None, rename=None):
    return {'from': [y, m], 'to': [y2, m2], 'label': label, 'note': note,
            'provinceRename': rename or {}, 'merge': merge or {},
            'units': units or []}


def mrg(**kw):
    r = dict(BASE_MERGE)
    r.update(kw)
    return r


